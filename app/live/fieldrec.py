def encode(value, budget=None, depth=0):
    """Bounded detached input snapshot; JSON serialization belongs to the writer.

    Larger than audit evidence to preserve 24-car fields and full rule snapshots.
    Every traversal (including sets) is bounded; cyclic inputs stop at depth 10.
    """
    if budget is None:
        budget = [4096, 32768]
    if budget[0] <= 0 or depth >= 10:
        return raceaudit.TRUNCATED
    budget[0] -= 1
    child = lambda v: encode(v, budget, depth + 1)
    if isinstance(value, Field):
        samples = {c: Sample(p, value.epoch.get(c, 0), value.generation.get(c, 0),
                             value.stamp.get(c, 0.0), value.since.get(c, 0.0), value.completed_laps.get(c))
                   for c, p in islice(value.progress.items(), 64)}
        result = {"$field": child(samples), "session": child(value.session)}
        if len(value.progress) > len(samples):
            result[raceaudit.TRUNCATED] = len(value.progress) - len(samples)
        return result
    if isinstance(value, Sample):
        return {"$sample": child(value._asdict()), "connected": True}
    if isinstance(value, dict):
        result = {}
        for k, v in islice(value.items(), 64):
            if budget[0] < 2:
                break
            result[child(k)] = child(v)
        if len(result) < len(value):
            result[raceaudit.TRUNCATED] = len(value) - len(result)
        return result
    if isinstance(value, (list, tuple, set)):
        result = []
        for v in islice(value, 64):
            if budget[0] <= 0:
                break
            result.append(child(v))
        if len(result) < len(value):
            result.append(raceaudit.TRUNCATED)
        return result
    if isinstance(value, str):
        size = min(512, budget[1])
        budget[1] -= min(len(value), size)
        return value if len(value) <= size else value[:size] + raceaudit.TRUNCATED
    return raceaudit._snapshot(value, budget, depth)


def capture(lock):
    """Snapshot outer calls under the state owner's lock; nested calls replay naturally."""
    def decorate(method):
        signature = inspect.signature(method)

        @wraps(method)
        def wrapped(self, *args, **kwargs):
            if getattr(self, "_fieldrec_replay", False) or not enabled(self.server_id):
                return method(self, *args, **kwargs)
            with lock:
                if getattr(self, "_fieldrec_depth", False):
                    return method(self, *args, **kwargs)
                clock = self.clock
                wall, mono = clock.time(), clock.monotonic()

                if not hasattr(self, "_fieldrec_session"):
                    self._fieldrec_session = str(int(wall * 1000)) + "-" + uuid.uuid4().hex
                    self._fieldrec_seq = 0
                self._fieldrec_seq += 1
                with raceaudit._lock:
                    admitted = not (raceaudit._closed or raceaudit._pending.full())
                    if not admitted:
                        raceaudit._counts["dropped"] += 1
                if admitted:
                    try:
                        bound = signature.bind(self, *args, **kwargs)
                        bound.apply_defaults()
                        arguments = {k: v for k, v in bound.arguments.items() if k != "self"}
                        # The slot and pace suffice; the GUID is only for following a driver.
                        arguments.pop("guid", None)
                        event = {
                            "format": FORMAT, "kind": method.__name__, "server_id": self.server_id,
                            "session": self._fieldrec_session, "seq": self._fieldrec_seq,
                            "ts": wall, "monotonic": mono,
                            "session_type": (self.session_ref or {}).get("session_type"),
                            "context": encode({
                                "neutralization_rule": self.neutralization_rule, "gb_rule": self.gb_rule,
                                "neutralization_excluded": self.neutralization_excluded,
                                "auto_off": self.auto_off, "auto_yellow": self.auto_yellow,
                                "flag_modes": self.flag_modes,
                                "pace_car": self.pace_car, "pace_car_kmh": self.pace_car_kmh,
                                "formation": self.formation,
                                "pace_guid": "configured" if self.pace_guid else "",
                            }),
                            "flag": self.flag, "in_pit": encode([c for c, t in islice(self._pit_seen.items(), 64) if wall - t < 30]),
                            "nascar": self.nascar is not None,
                            "args": encode(arguments),
                            # Pre-entry identities survive globally allocated obligation IDs.
                            "obligations": encode(list(islice(self.giveback._open.values(), 64)) if self.giveback else []),
                        }
                        raceaudit.enqueue(event)
                    except Exception:  # noqa: BLE001 - recording must never affect racing
                        with raceaudit._lock:
                            raceaudit._counts["errors"] += 1
                self.clock = SimpleNamespace(time=lambda: wall, monotonic=lambda: mono)
                self._fieldrec_depth = True
                try:
                    return method(self, *args, **kwargs)
                finally:
                    self._fieldrec_depth = False
                    self.clock = clock
        wrapped._fieldrec_captured = True
        return wrapped
    return decorate


def stats():
    """Shared admission/persistence counters, including audit and field tape drops."""
    return raceaudit.stats()


def close(timeout=8):
    """The shared writer drains both tapes within this timeout."""
    return raceaudit.close(timeout)
